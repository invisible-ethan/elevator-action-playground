const CHARS = Object.keys(GLYPHS);
const INDEX = new Map(CHARS.map((c, i) => [c, i]));
const atlases = new Map<string, HTMLCanvasElement>();

function atlas(color: string): HTMLCanvasElement {
  let canvas = atlases.get(color);
  if (canvas) return canvas;
  canvas = document.createElement('canvas');
  canvas.width = CHARS.length * 8;
  canvas.height = 8;
  const ctx = canvas.getContext('2d')!;
  ctx.fillStyle = color;
  CHARS.forEach((c, i) => {
    GLYPHS[c].forEach((row, y) => {
      for (let x = 0; x < 5; x++) {
        if (row & (0x10 >> x)) ctx.fillRect(i * 8 + x + 1, y, 1, 1);
      }
    });
  });
  atlases.set(color, canvas);
  return canvas;
}

export const textWidth = (text: string, scale = 1) => text.length * 8 * scale;

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void {
  const img = atlas(color);
  const s = text.toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const idx = INDEX.get(s[i]);
    if (idx === undefined) continue;
    ctx.drawImage(img, idx * 8, 0, 8, 8, Math.round(x + i * 8 * scale), Math.round(y), 8 * scale, 8 * scale);
  }
}

export function drawTextCentered(
  ctx: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color: string,
  scale = 1,
): void {
  drawText(ctx, text, cx - textWidth(text, scale) / 2, y, color, scale);
}
